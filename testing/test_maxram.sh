#!/bin/bash
# --maxramdrive (0.9.1): -m lets pi_clean mount its own RAM disk for a
# compressed-image extract — auto-sized to what the image needs plus a
# small buffer, and only when the system has that much RAM to spare
# (MemAvailable).  Existing RAM disks always come first.
#
# The own-tmpfs behaviour is verified in REAL inside `sudo unshare -m`: there
# every inherited tmpfs gets a fresh small one mounted OVER the same point
# (not a remount — a remount reconfigures the superblock shared with the
# host and would change the host's sizes), so the existing disks cannot
# hold the fixture.  Phases: nom = no -m (disk, no RAM note at all);
# notafford = -m but the image exceeds what the system can spare
# (message + disk); own = -m and affordable (a real own tmpfs mount, sized
# ~= need + 8 MiB, measured).  After each phase the suite asserts the host's
# tmpfs sizes are exactly as before.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
P=$(cd "$HERE/.." && pwd)/pi_clean.sh
# shared rootfs fixture (regenerated by make_base_fix.sh when missing)
[[ -e /tmp/pi_clean_test/base_fix/etc/os-release ]] || bash "$HERE/make_base_fix.sh"
# scratch on REAL disk (the ns phase overlays every tmpfs with a small one,
# so tmpfs paths inside the namespace are not safe scratch)
D=/var/tmp/pi_clean_test_maxram
rm -rf "$D"; mkdir -p "$D"
cp "$P" "$D/pi_clean.sh"
# fixture: a plausible xz-compressed image (any payload)
tar -C /tmp/pi_clean_test -cf - base_fix 2>/dev/null | xz -c > "$D/image.img.xz"

# the shim + stage live on REAL disk: the ns phase replaces the host's /tmp
# with a small overlay, which would hide /tmp paths inside the namespace
SHIM=/var/tmp/pi_clean_test_maxram_shim
rm -rf "$SHIM"; mkdir -p "$SHIM"
STAGE=/var/tmp/pi_clean_test_maxram_stage
rm -rf "$STAGE"; mkdir -p "$STAGE"
cp -a /tmp/pi_clean_test/base_fix/. "$STAGE/"
export SHIM_STAGE="$STAGE"
# mount shim: dispatch — pi_clean's own tmpfs mount (form: mount -t tmpfs -o
# ... tmpfs MP) goes to the REAL mount(8); the emulated rootfs attach
# (form: mount -o rw DEV MP) gets the staged content, as in test_imgxz.sh.
cat > "$SHIM/mount" <<'EOF'
#!/bin/bash
if [[ "${1:-}" == -t && "${2:-}" == tmpfs ]]; then exec /usr/bin/mount "$@"; fi
dev=$3; mp=$4
[[ $dev == /dev/loop0 ]] || exit 32
cp -a "${SHIM_STAGE:?}/." "$mp/"
exit 0
EOF
# umount shim: emulated rootfs points -> empty the dir; real points (the own
# tmpfs) -> umount for real.  Always exit 0 (as with a real busy-free umount).
cat > "$SHIM/umount" <<'EOF'
#!/bin/bash
mp=${1:-}
[[ -n $mp && -d $mp ]] && find "$mp" -mindepth 1 -delete 2>/dev/null
/usr/bin/umount "$mp" 2>/dev/null
exit 0
EOF
cat > "$SHIM/losetup" <<'EOF'
#!/bin/bash
case $* in -d*) exit 0 ;; esac
[[ -n ${SHIM_FAILALL:-} ]] && exit 1
echo /dev/loop0
EOF
chmod +x "$SHIM/losetup" "$SHIM/mount" "$SHIM/umount"

PASS=0; FAIL=0
pass() { echo "PASS  $1"; PASS=$((PASS+1)); }
fail() { echo "FAIL  $1"; FAIL=$((FAIL+1)); }
t() { desc=$1; want=$2; shift 2
    out=$("$@" 2>&1); rc=$?
    if [[ $rc == "$want" ]]; then echo "PASS (rc=$rc): $desc"; else
        echo "FAIL (rc=$rc want=$want): $desc"; printf '%s\n' "$out" | head -6; return 1; fi }
cleanres() {  # no leftover own-mount dirs or extracts anywhere
    local l
    l=$(find /dev/shm /run /var/tmp "$D" -maxdepth 1 -name 'pi_clean.*' \
            ! -name 'pi_clean.sh' 2>/dev/null)
    l+=$'\n'$(find /tmp -maxdepth 1 -name 'pi_clean.*' ! -name 'pi_clean.sh' 2>/dev/null)
    if [[ -n ${l//[[:space:]]/} ]]; then
        echo "FAIL: leftovers: $(printf '%s' "$l" | tr -s '[:space:]' ' ')"; return 1
    fi
    echo "PASS: no leftovers"
}
hoststate() {  # the size column of the main host tmpfses (set -u safe)
    df -Pk /tmp /dev/shm /run /run/lock /run/user/1000 2>/dev/null \
        | awk 'NR>1 { printf "%s:%s ", $1, $2 }'
}
hostok() {  # the ns phase must not have leaked remounts to the host
    local now; now=$(hoststate)
    [[ $now == "${HOST_SNAP:-}" ]] && pass "host tmpfs sizes untouched" \
                          || { fail "host tmpfs sizes CHANGED (was: $HOST_SNAP | now: $now)"; return 1; }
}

echo "=== 1) parse layer (flag form; old size form refused with a hint) ==="
t "-m 9G (old form) is refused"            2 bash "$D/pi_clean.sh" -m 9G
t "--maxramdrive 8G (old form) refused"    2 bash "$D/pi_clean.sh" --maxramdrive 8G
t "-maxramdrive 4096MB (old form) refused" 2 bash "$D/pi_clean.sh" -maxramdrive 4096MB
t "-m 0 (old form) is refused"             2 bash "$D/pi_clean.sh" -m 0
hint=$(bash "$D/pi_clean.sh" -m 9G 2>&1)
[[ $hint == *"no longer takes a size"* && $hint == *"Drop the size argument"* ]] \
    && pass "old form: the migration hint says it now sizes itself" \
    || fail "old form: missing the migration hint (got: $hint)"
h=$(bash "$D/pi_clean.sh" -h 2>&1)
[[ $h == *"-m, --maxramdrive"* && $h != *"-m SIZE"* ]] \
    && pass "-h shows the flag form (no SIZE argument)" \
    || fail "-h is wrong for --maxramdrive (got: $h)"
ver=$(bash "$D/pi_clean.sh" -V)
[[ $ver == "pi_clean 0.9.1" ]] && pass "-V reports 0.9.1" || fail "-V: got: <$ver>"

echo "=== 2) existing RAM disk still wins (host: big tmpfs present) ==="
note=$(PATH="$SHIM:$PATH" bash "$D/pi_clean.sh" "$D/image.img.xz" -m -t 2>&1 >/dev/null)
[[ $note == *"extracting to RAM:"* && $note != *"own mount"* ]] \
    && pass "-m given but an existing tmpfs fits -> uses the existing one" \
    || fail "-m/existing precedence (note: $note)"
cleanres

echo "=== 3) inside an isolated mount namespace ==="
HOST_SNAP=$(hoststate)
# No remounts here: a remount reconfigures the tmpfs SUPERBLOCK, and the
# superblock is shared with the host, so the change leaks out of the
# namespace (that is how an earlier draft shrank the host's /tmp and
# /dev/shm).  Instead every inherited tmpfs gets a fresh small instance
# mounted over the same point (mount-over-mount): local to this namespace,
# and the host's instances stay intact underneath.  hostok() after each
# phase proves the host's sizes never moved.
ns_run() {  # ns_run <want-rc> <desc> <mode: nom|notafford|own>
    local want=$1 desc=$2 mode=$3
    NS_STDERR=$(sudo unshare -m bash -c '
        set -u
        shim=$1; d=$2; mode=$3; stage=$4; shift 4
        export SHIM_STAGE=$stage        # sudo drops the outer environ
        # sever mount-event propagation (defence in depth; the real
        # guarantee is that the overlays below are fresh mounts, never
        # remounts, so the host superblocks are never reconfigured)
        /usr/bin/mount --make-rprivate / || exit 75
        # overlay every tmpfs with a fresh small one over the same point.
        # Snapshot /proc/mounts first: each overlay appends a line to the
        # live table, so reading it while going would never reach EOF
        mounts=$(cat /proc/mounts)
        while read -r _ mp fstype _; do
            [[ $fstype == tmpfs ]] || continue
            # a point under an already-overlaid parent (e.g. /run/lock
            # under /run) no longer exists in this namespace: skip it
            [[ -d $mp ]] || continue
            u=$(df -Pk "$mp" 2>/dev/null | awk "NR==2 {print \$3}")
            u=${u%%[^0-9]*}; u=${u:-0}
            /usr/bin/mount -t tmpfs -o "size=$(( u / 1024 + 2 ))M" tmpfs "$mp" || exit 75
        done <<< "$mounts"
        # F = the best free space left on any existing tmpfs (bytes)
        F=0
        while read -r _ mp fstype _; do
            [[ $fstype == tmpfs ]] || continue
            k=$(df -Pk "$mp" 2>/dev/null | awk "NR==2 {print \$4}")
            [[ ${k:-} =~ ^[0-9]+$ ]] && (( k * 1024 > F )) && F=$(( k * 1024 ))
        done < /proc/mounts
        # fixture raw size by phase:
        #  notafford: raw = 5/4 of the MemAvailable spare, so need = raw*1.1
        #             is ~1.4x MemAvailable - the own-mount gate must refuse
        #  nom/own:   raw = 95% of the best free existing tmpfs + 1 MiB, so
        #             no existing disk fits, while the extract stays small
        if [[ $mode == notafford ]]; then
            memkb=0
            while read -r key val _; do
                [[ $key == MemAvailable: ]] && { memkb=$val; break; }
            done < /proc/meminfo
            raw=$(( memkb * 1024 * 5 / 4 ))
        else
            raw=$(( F * 95 / 100 + 1048576 ))
            (( raw > 3221225472 )) && raw=3221225472
        fi
        need=$(( raw + raw / 10 ))
        # zero-filled fixture whose decompressed size xz -l reports is ~raw
        dd if=/dev/zero bs=1M count=$(( (raw + 1048575) / 1048576 )) 2>/dev/null \
            | xz -T0 -c > "$d/image.img.xz" || exit 75
        # the own phase: sample /proc/mounts while the run happens, to read
        # the size= option of the own mount (pi_clean unmounts it on exit, so
        # the suite has no other way to see what was actually mounted).
        # pi_clean sizes it to need + 8 MiB; capture the real value and check
        # it here.
        cap="$d/cap.txt"
        rm -f "$cap"
        sam=""
        [[ $mode == own ]] && {
            (
                i=0
                while (( i < 240 )); do
                    while read -r _ mp fst opts rest; do
                        [[ $fst == tmpfs && $mp == *pi_clean.ram* ]] || continue
                        case $opts in
                            *size=*) s=${opts#*size=}
                                    s=${s%%,*}
                                    s=${s//[!0-9]/}   # kernel echoes "K" back lowercase
                                    [[ -n $s ]] && printf "%s\n" "$s" >> "$cap" ;;
                        esac
                    done < /proc/mounts
                    sleep 0.25
                    i=$(( i + 1 ))
                done
            ) &
            sam=$!
        }
        set -- bash "$d/pi_clean.sh" "$d/image.img.xz" -t
        [[ $mode != nom ]] && set -- "$@" -m
        PATH="$shim:$PATH" "$@"
        rc=$?
        [[ -n $sam ]] && kill $sam 2>/dev/null
        [[ $mode == own ]] && {
            got=$(sort -n "$cap" 2>/dev/null | tail -1)
            exp=$(( (need + 8388607) / 1024 ))
            if [[ ${got:-} =~ ^[0-9]+$ ]]; then
                delta=$(( got > exp ? got - exp : exp - got ))
                if (( delta <= 2048 )); then
                    echo "auto size OK (mounted=${got}K, expected=${exp}K, delta=${delta}K)"
                else
                    echo "auto size MISMATCH (mounted=${got}K, expected=${exp}K)"
                fi
            else
                echo "auto size MISMATCH (own mount never seen in /proc/mounts)"
            fi
        }
        exit $rc
    ' __ "$SHIM" "$D" "$mode" "$STAGE" 2>&1); local rc=$?
    if [[ $rc == "$want" ]]; then echo "PASS (rc=$rc): $desc"; else
        echo "FAIL (rc=$rc want=$want): $desc"; printf '%s\n' "$NS_STDERR" | head -8; return 1; fi
}

echo "--- 3a) no -m: nothing fits any RAM disk -> disk fallback"
ns_run 0 "no -m: extract goes to the real disk, never an own mount" nom
[[ $NS_STDERR != *"extracting to RAM"* ]] && pass "no -m: no RAM-disk note at all" \
    || fail "no -m: unexpected RAM note (got: $NS_STDERR)"
cleanres
hostok

echo "--- 3b) -m, but the system cannot spare that much RAM: told, then disk"
ns_run 0 "-m + not affordable: refused for the extract, disk used" notafford
[[ $NS_STDERR == *"a RAM disk would need"* && $NS_STDERR == *"to spare"* \
   && $NS_STDERR == *"using disk"* ]] \
    && pass "notafford: the refusal message (need, spare, disk) is said" \
    || fail "notafford: missing the refusal message (got: $NS_STDERR)"
cleanres
hostok

echo "--- 3c) -m, and the system can afford it: the own tmpfs mount takes the extract"
ns_run 0 "-m affordable: extract lands on an own, real tmpfs mount" own
[[ $NS_STDERR == *"extracting to RAM (own mount, sized to"* ]] \
    && pass "own: the own-mount extract is announced on stderr" \
    || fail "own: missing the own-mount note (got: $NS_STDERR)"
[[ $NS_STDERR == *"auto size OK"* ]] \
    && pass "own: the mounted size ~= need + 8 MiB (measured via /proc/mounts)" \
    || fail "own: auto size not OK (got: $NS_STDERR)"
cleanres
hostok

echo
echo "== test_maxram: PASS=$PASS FAIL=$FAIL"
(( FAIL == 0 ))
